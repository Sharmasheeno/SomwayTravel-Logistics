import postcss from 'postcss';
import fs from 'node:fs';
const files=['app/globals.css','app/somway.css','somway_ui_handoff/src/styles.css','app/somway-handoff-compat.css'];
const out=postcss.root();
function rgb(token) {
  if(token==='white')return [255,255,255];
  if(token==='black')return [0,0,0];
  if(token.startsWith('#')) {let h=token.slice(1);if(h.length===3||h.length===4)h=h.split('').map(x=>x+x).join('');return [0,2,4].map(i=>parseInt(h.slice(i,i+2),16));}
  return token.match(/[\d.]+/g)?.slice(0,3).map(Number);
}
const colors=/#(?:[\da-f]{8}|[\da-f]{6}|[\da-f]{4}|[\da-f]{3})\b|rgba?\([^)]*\)|(?<![\w-])white\b|(?<![\w-])black\b/gi;
for(const file of files) {
 const root=postcss.parse(fs.readFileSync(file,'utf8'));
 root.walkRules(rule=>{
   if(rule.selector.includes('data-theme')||rule.selector.includes(':root'))return;
   const parents=[];let p=rule.parent;
   while(p&&p.type!=='root'){if(p.type==='atrule')parents.unshift(p);p=p.parent;}
   if(parents.some(p=>p.name.includes('keyframes')||p.params?.includes('print')))return;
   const declarations=[];
   rule.nodes?.filter(n=>n.type==='decl').forEach(d=>{
     if(!/^(background(-color)?|color|border(-.*)?|fill|stroke)$/.test(d.prop))return;
     let changed=false;
     const value=d.value.replace(colors,token=>{
       const c=rgb(token.toLowerCase());if(!c||c.length<3)return token;
       const l=(c[0]*.2126+c[1]*.7152+c[2]*.0722)/255;
       let replacement;
       if(d.prop.startsWith('background')&&l>.70) replacement='var(--surface)';
       else if(d.prop==='color'&&l<.62)replacement='var(--ink)';
       else if(d.prop.startsWith('border')&&l>.5)replacement='var(--line)';
       if(replacement){changed=true;return replacement;}return token;
     });
     if(changed)declarations.push({prop:d.prop,value,important:d.important});
   });
   if(!declarations.length)return;
   const selectors=rule.selectors.map(s=>/^(html|body)(\b|[.:#\[])/.test(s)?s.replace(/^html/,'html[data-theme="dark"]').replace(/^body/,'html[data-theme="dark"] body'):`html[data-theme="dark"] ${s}`);
   let target=out;for(const a of parents){const clone=postcss.atRule({name:a.name,params:a.params});target.append(clone);target=clone;}
   target.append(postcss.rule({selector:selectors.join(',\n'),nodes:declarations.map(d=>postcss.decl(d))}));
 });
}
fs.writeFileSync('app/theme-components.css','/* Generated by scripts/build-theme-overrides.mjs from component color declarations. */\n'+out.toString());
console.log(`Generated ${out.nodes.length} scoped theme rules.`);
