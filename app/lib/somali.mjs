export const normalizeCopy = text => text.replace(/&amp;/g, '&').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim().toLowerCase();
export const somali = Object.fromEntries(entries.trim().split('\n').map(line => {
  const divider = line.indexOf('|');
  return [normalizeCopy(line.slice(0, divider)), line.slice(divider + 1)];
}));
export function translateCopy(text, locale = 'en', values) {
  if (typeof text !== 'string') return text;
  const translated = locale === 'so' ? somali[normalizeCopy(text)] ?? text : text;
  return values ? translated.replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? '')) : translated;
}
